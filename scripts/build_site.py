#!/usr/bin/env python3
"""Build a self-contained GitHub Pages site without symlinks or remote assets."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--include-downloads', action='store_true', help='Include original ZIPs for a completely offline local site')
parser.add_argument('--output', type=Path, default=ROOT / '_site')
args = parser.parse_args()
output = args.output.resolve()
# Only replace a dedicated build output, never the source checkout.
if output == ROOT or ROOT.is_relative_to(output) or output in [ROOT / p for p in ['web', 'site', 'archive', 'scripts', 'verification']]:
    raise SystemExit('Output must be a separate build directory')
if output.exists():
    if not (output / '.hover-build').exists():
        raise SystemExit('Refusing to replace a directory without .hover-build marker')
    shutil.rmtree(output)
output.mkdir(parents=True)
(output / '.hover-build').write_text('Generated by scripts/build_site.py\n')
shutil.copytree(ROOT / 'site', output, dirs_exist_ok=True)
# Shared files are published once; path aliases are normalized below.
omitted = []
for source in (ROOT / 'web/assets').rglob('*'):
    if source.is_symlink() or not source.is_file():
        continue
    relative = source.relative_to(ROOT / 'web/assets')
    # Keep the complete archive in Git; publish only runtime texture variants.
    if relative.parts[0] == 'Images':
        omitted.append({'path': str(relative), 'bytes': source.stat().st_size, 'reason': 'byte-identical capitalization duplicate; URLs normalized to images/'})
        continue
    if 'Schemes' in relative.parts or relative.parts[:2] == ('3d', 'Textures'):
        # SchemeLoader uses JPG diffuse textures, except PNG decals and ARM quarter PNGs.
        # Models use JPG diffuse textures; effects use half normals and quarter glow maps.
        scheme = 'Schemes' in relative.parts
        original_diffuse = source.suffix.lower() == '.jpg' and not re.search(r'_(?:NORMALS?|GLOW|HALF|QUARTER)', source.stem)
        decal = scheme and source.name.startswith('DECAL_') and source.suffix.lower() == '.png' and not re.search(r'_(?:NORMALS?|GLOW|HALF|QUARTER)', source.stem)
        arm_diffuse = scheme and source.name.endswith('_QUARTER.png') and not re.search(r'_(?:NORMALS?|GLOW|HALF|QUARTER)', source.stem[:-8])
        effect = source.name.endswith(('_NORMAL_HALF.png', '_NORMALS_HALF.png', '_GLOW_QUARTER.png'))
        if not ('Retro' in relative.parts or original_diffuse or decal or arm_diffuse or effect):
            omitted.append({'path': str(relative), 'bytes': source.stat().st_size, 'reason': 'export variant not selected by SchemeLoader or model texture paths'})
            continue
    target = output / 'assets' / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)

for date, name in [('2013-10-02', 'early'), ('2019-03-11', 'latest')]:
    source = ROOT / 'web' / date
    target = output / 'play' / name
    target.mkdir(parents=True)
    for file in source.rglob('*'):
        if file.is_symlink() or not file.is_file():
            continue
        dest = target / file.relative_to(source)
        dest.parent.mkdir(parents=True, exist_ok=True)
        text = file.read_text()
        # Resource URLs resolve against the document (JS/HTML) or stylesheet (CSS).
        prefix = '../../../assets/' if file.suffix == '.css' else '../../assets/'
        text = re.sub(r'(?<![A-Za-z0-9_.:/-])(?:\.\./|/)?(Images|images|3d|fonts|sounds)/',
                      lambda m: prefix + ('images' if m[1] == 'Images' else m[1]) + '/', text)
        text = re.sub(r'/MAZE([123])/', r'/Maze\1/', text)
        if file.name == 'index.html':
            text = re.sub(r'<link[^>]*rethinkbar[^>]*>', '', text)
            text = text.replace('<body>', '<body>\n<a class="archive-back" href="../../">← ARCHIV</a>')
            text = text.replace('</head>', '<style>.archive-back{position:fixed;left:12px;bottom:9px;z-index:10000;padding:5px 9px;background:#130d24dc;border:1px solid #6b4a81;color:#e9d5ff;font:11px Arial;text-decoration:none}.archive-back:focus-visible{outline:2px solid #ffb36b}</style></head>')
        if file.suffix == '.css':
            # Segoe UI was used by the IE advertising panel; local font fallback remains.
            text = re.sub(r'@font-face\s*\{[^{}]*https?://i\.s-microsoft\.com/[^{}]*\}', '', text)
        if file.name.startswith('game.') and file.suffix == '.js':
            # Retro insertion must find the scheme directory after adding the Pages asset prefix.
            text = text.replace('"Schemes"===p[2]', 'p.indexOf("Schemes")!==-1')
            # Keep the old information panel local; its external YouTube player is not archived.
            text = re.sub(r'http://img\.youtube\.com/vi/.*?/maxresdefault\.jpg', '../../assets/images/UI/hover_fb.png', text)
        dest.write_text(text)
# A third opt-in derivative shares assets; both restored releases stay unchanged.
modified = output / 'play/modified'
shutil.copytree(output / 'play/latest', modified)
shutil.copytree(ROOT / 'modifications', modified, dirs_exist_ok=True)
index = modified / 'index.html'
html = index.read_text().replace('<title>Hover!</title>', '<title>Hover! — Touch + Vollbild</title>')
html = html.replace('</head>', '<link rel="stylesheet" href="modern.css">\n<script src="../../mobile.js"></script>\n</head>')
html = html.replace('</body>', '<script src="modern.js"></script>\n</body>')
html = html.replace('width=device-width"', 'width=device-width,viewport-fit=cover"')
index.write_text(html)
if args.include_downloads:
    subprocess.run([sys.executable, str(ROOT / 'scripts/restore_windows.py'), '--output', str(output / 'downloads')], check=True)
else:
    index = output / 'index.html'
    html = index.read_text()
    for download in json.loads((ROOT / 'archive/windows/release-downloads.json').read_text()):
        html = html.replace('href="downloads/' + download['original_filename'] + '"', 'href="' + download['url'] + '"')
    index.write_text(html)
(output / '.nojekyll').touch()
(output / 'asset-selection.json').write_text(json.dumps({'omitted_from_pages_only': omitted}, indent=2) + '\n')
manifest = {str(p.relative_to(output)): {'size': p.stat().st_size, 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
            for p in output.rglob('*') if p.is_file() and p.name != '.hover-build'}
(output / 'checksums.json').write_text(json.dumps(manifest, indent=2) + '\n')
assert not any(p.is_symlink() for p in output.rglob('*'))
print(f'Built {len(manifest)} files in {output}')
